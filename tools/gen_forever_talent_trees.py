#!/usr/bin/env python3
"""Generate Flavors/Forever/TalentTrees.lua from the Forever sim's talent trees.

Usage: gen_forever_talent_trees.py <path to wowsims/forever checkout> > Flavors/Forever/TalentTrees.lua

Reads ui/sim/talents/trees/<class>.json. Talents stay in the order the sim lists them, which is the
digit order of a talent string.
"""
import json
import subprocess
import sys
from pathlib import Path

CLASSES = ["druid", "hunter", "mage", "paladin", "priest", "rogue", "shaman", "warlock", "warrior"]


def lua_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    root = Path(sys.argv[1])
    commit = subprocess.run(["git", "-C", str(root), "rev-parse", "--short", "HEAD"],
                            capture_output=True, text=True).stdout.strip() or "unknown"
    out = [
        "-- Talent trees of every Forever class: position, spell and max rank of each talent, in",
        "-- talent string order. Generated by tools/gen_forever_talent_trees.py from the Forever sim",
        f"-- (wowsims/forever, ui/sim/talents/trees, commit {commit}). Don't edit by hand.",
        "",
        "local _, Env = ...",
        "",
        "-- [classFile] = { { name, talents = { { row, column, spell, max, name[, prereqRow, prereqColumn] }, ... } }, ... }",
        "-- row and column start at 1.",
        "Env.ForeverTalentTrees = {",
    ]
    for cls in CLASSES:
        trees = json.loads((root / "ui/sim/talents/trees" / f"{cls}.json").read_text())
        out.append(f"    {cls.upper()} = {{")
        for tree in trees:
            out.append(f"        {{ name = {lua_string(tree['name'])}, talents = {{")
            for talent in tree["talents"]:
                loc = talent["location"]
                out.append(
                    f"            {{ {loc['rowIdx'] + 1}, {loc['colIdx'] + 1}, {talent.get('spellId', 0)}, "
                    f"{talent['maxPoints']}, {lua_string(talent.get('fancyName', ''))}"
                    + (f", {talent['prereqLocation']['rowIdx'] + 1}, {talent['prereqLocation']['colIdx'] + 1}"
                       if talent.get("prereqLocation") else "")
                    + " },")
            out.append("        } },")
        out.append("    },")
    out.append("}")
    print("\n".join(out))


if __name__ == "__main__":
    main()
